#!/usr/bin/env bash
# Standalone build entrypoint for the native ov_bench C++ executable.
#
# Resolves the OpenVINO SDK / runtime library paths, configures and builds the
# `ov_bench` target (CMake, Release) and verifies the result. On success it
# writes <build-dir>/ov_bench_runtime.env with the runtime library path.
#
# Examples:
#   bash scripts/build_cpp.sh --openvino-dir /path/to/openvino/cmake
#   bash scripts/build_cpp.sh --openvino-libs /path/to/lib/intel64
#   bash scripts/build_cpp.sh --openvino-so /path/to/libopenvino.so
#
# Environment overrides: OPENVINO_DIR, OPENVINO_LIB_DIR, OPENVINO_SO_PATH,
# BUILD_DIR, BUILD_JOBS, DRY_RUN.
set -euo pipefail

CPP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

OPENVINO_DIR="${OPENVINO_DIR:-}"
OPENVINO_LIB_DIR="${OPENVINO_LIB_DIR:-}"
OPENVINO_SO_PATH="${OPENVINO_SO_PATH:-}"
BUILD_DIR="${BUILD_DIR:-$CPP_DIR/build}"
BUILD_JOBS="${BUILD_JOBS:-8}"
DRY_RUN="${DRY_RUN:-0}"

usage() {
	cat <<'EOF'
Usage: bash scripts/build_cpp.sh [options]

Build the native ov_bench executable (CMake, Release).

  --openvino-dir DIR     OpenVINO CMake package directory (contains OpenVINOConfig.cmake)
  --openvino-libs DIR    OpenVINO runtime lib directory; the CMake package is
                         discoverable from it (cmake/openvino*, ../runtime/cmake, ...)
  --openvino-so FILE     Path to libopenvino.so (sets the lib directory)
  --build-dir DIR        Build output directory (default: <repo>/build)
  --jobs N               Parallel build jobs (default: 8)
  --dry-run              Print the resolved configuration without building
  -h, --help             Show this help

After a successful build:
  source <build-dir>/ov_bench_runtime.env
EOF
}

while (($#)); do
	case "$1" in
		-h|--help) usage; exit 0 ;;
		--dry-run) DRY_RUN=1; shift; continue ;;
	esac
	(($# >= 2)) || { echo "Missing value for $1" >&2; exit 2; }
	[[ "$2" != --* ]] || { echo "Missing value for $1" >&2; exit 2; }
	case "$1" in
		--openvino-dir) OPENVINO_DIR="$2" ;;
		--openvino-libs) OPENVINO_LIB_DIR="$2" ;;
		--openvino-so) OPENVINO_SO_PATH="$2" ;;
		--build-dir) BUILD_DIR="$2" ;;
		--jobs) BUILD_JOBS="$2" ;;
		*) echo "Unsupported option: $1; see --help" >&2; exit 2 ;;
	esac
	shift 2
done

BINARY="$BUILD_DIR/ov_bench"

if [[ -n "$OPENVINO_SO_PATH" ]]; then
	if [[ ! -f "$OPENVINO_SO_PATH" ]]; then
		echo "OpenVINO so path not found: $OPENVINO_SO_PATH" >&2
		exit 1
	fi
	OPENVINO_LIB_DIR="$(cd "$(dirname "$OPENVINO_SO_PATH")" && pwd)"
fi

if [[ -n "$OPENVINO_LIB_DIR" && ! -d "$OPENVINO_LIB_DIR" ]]; then
	echo "OpenVINO lib dir not found: $OPENVINO_LIB_DIR" >&2
	exit 1
fi

# Derive OPENVINO_DIR from the lib dir when only the so/lib path was provided.
if [[ -z "$OPENVINO_DIR" && -n "$OPENVINO_LIB_DIR" ]]; then
	for candidate in \
		"$OPENVINO_LIB_DIR/cmake/openvino"* \
		"$OPENVINO_LIB_DIR/cmake" \
		"$OPENVINO_LIB_DIR/../lib/cmake/openvino"* \
		"$OPENVINO_LIB_DIR/../cmake" \
		"$OPENVINO_LIB_DIR/../../cmake" \
		"$OPENVINO_LIB_DIR/../runtime/cmake" \
		"$OPENVINO_LIB_DIR/../../runtime/cmake"; do
		if [[ -f "$candidate/OpenVINOConfig.cmake" ]]; then
			OPENVINO_DIR="$(cd "$candidate" && pwd)"
			break
		fi
	done
	if [[ -z "$OPENVINO_DIR" ]]; then
		found_config="$(find "$OPENVINO_LIB_DIR" "$(dirname "$OPENVINO_LIB_DIR")" -maxdepth 5 -name OpenVINOConfig.cmake 2>/dev/null | head -n1 || true)"
		if [[ -n "$found_config" ]]; then
			OPENVINO_DIR="$(cd "$(dirname "$found_config")" && pwd)"
		fi
	fi
fi

if [[ -z "$OPENVINO_DIR" ]]; then
	echo "An OpenVINO CMake package is required: pass --openvino-dir DIR (or --openvino-libs / --openvino-so with a discoverable package)" >&2
	exit 2
fi
if [[ ! -f "$OPENVINO_DIR/OpenVINOConfig.cmake" ]]; then
	echo "OpenVINOConfig.cmake not found in: $OPENVINO_DIR" >&2
	exit 1
fi

if (( DRY_RUN == 1 )); then
	echo "[DRY-RUN] BINARY=$BINARY"
	echo "[DRY-RUN] OPENVINO_DIR=$OPENVINO_DIR"
	echo "[DRY-RUN] OPENVINO_LIB_DIR=${OPENVINO_LIB_DIR:-<unset>}"
	echo "[DRY-RUN] BUILD_JOBS=$BUILD_JOBS"
	exit 0
fi

mkdir -p "$BUILD_DIR"
cmake -S "$CPP_DIR" -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release -DOpenVINO_DIR="$OPENVINO_DIR"
cmake --build "$BUILD_DIR" --target ov_bench -j "$BUILD_JOBS"

if [[ ! -x "$BINARY" ]]; then
	echo "Built binary not executable: $BINARY" >&2
	exit 1
fi

runtime_library_path=""
if [[ -n "$OPENVINO_LIB_DIR" && -d "$OPENVINO_LIB_DIR" ]]; then
	runtime_library_path="$OPENVINO_LIB_DIR"
	tbb_library_dir="$OPENVINO_LIB_DIR/../../3rdparty/tbb/lib"
	if [[ -f "$tbb_library_dir/libtbb.so.12" ]]; then
		runtime_library_path+=":$(cd "$tbb_library_dir" && pwd)"
	fi
fi
{
	printf '# ov_bench runtime environment (generated by scripts/build_cpp.sh)\n'
	printf 'BUILD_DIR="%s"\n' "$BUILD_DIR"
	printf 'BINARY="%s"\n' "$BINARY"
	if [[ -n "$runtime_library_path" ]]; then
		printf 'export LD_LIBRARY_PATH="%s${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"\n' "$runtime_library_path"
	fi
} > "$BUILD_DIR/ov_bench_runtime.env"

echo "Built: $BINARY"
echo "Runtime environment: source $BUILD_DIR/ov_bench_runtime.env"
